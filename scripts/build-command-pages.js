#!/usr/bin/env node
/**
 * Generates one page per command category so links like /commands/movies work
 * on GitHub Pages (which only serves real files).
 *
 *   docs/commands.html            ← the page you edit
 *   docs/commands/index.html      ← generated copy (/commands/)
 *   docs/commands/<category>.html ← generated, opens with that category selected
 *
 * Run after changing docs/commands.html or the categories in docs/js/commands-data.js:
 *   npm run docs:pages
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const DOCS = path.join(__dirname, '..', 'docs');
const SITE = 'https://www.hipphamster.online';

const template = fs.readFileSync(path.join(DOCS, 'commands.html'), 'utf8');

// Read categories and commands from the same data file the page uses
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(DOCS, 'js', 'commands-data.js'), 'utf8'), sandbox);
const categories = sandbox.window.IC_CATEGORIES;
const commands = sandbox.window.IC_COMMANDS;

const escapeAttr = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

function build({ title, description, url, initialCategory }) {
  let html = template;
  const replaceOnce = (pattern, replacement) => {
    if (!pattern.test(html)) throw new Error(`commands.html is missing ${pattern}`);
    html = html.replace(pattern, replacement);
  };

  replaceOnce(/<title>[^<]*<\/title>/, `<title>${escapeAttr(title)}</title>`);
  replaceOnce(
    /<meta name="description" content="[^"]*" \/>/,
    [
      `<meta name="description" content="${escapeAttr(description)}" />`,
      `  <link rel="canonical" href="${url}" />`,
      `  <meta property="og:title" content="${escapeAttr(title)}" />`,
      `  <meta property="og:description" content="${escapeAttr(description)}" />`,
      `  <meta property="og:url" content="${url}" />`,
      '  <meta name="theme-color" content="#FF6B35" />',
    ].join('\n'),
  );
  html = html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- Generated by scripts/build-command-pages.js from docs/commands.html — edit that file instead. -->');
  if (initialCategory) {
    replaceOnce(
      /(<script src="\/js\/commands-data\.js)/,
      `<script>window.IC_INITIAL_CATEGORY = ${JSON.stringify(initialCategory)};</script>\n$1`,
    );
  }
  return html;
}

const outDir = path.join(DOCS, 'commands');
fs.mkdirSync(outDir, { recursive: true });

// Remove stale category pages (e.g. a renamed category)
const keep = new Set(['index.html', ...categories.map((c) => `${c.id}.html`)]);
for (const f of fs.readdirSync(outDir)) {
  if (f.endsWith('.html') && !keep.has(f)) fs.unlinkSync(path.join(outDir, f));
}

fs.writeFileSync(
  path.join(outDir, 'index.html'),
  build({
    title: 'Commands — Insomniacs Bot',
    description: 'Browse and search every Insomniacs Bot command, with syntax, examples and parameters.',
    url: `${SITE}/commands`,
  }),
);

for (const cat of categories) {
  const names = commands.filter((c) => c.category === cat.id).map((c) => `/ic ${c.name}`);
  fs.writeFileSync(
    path.join(outDir, `${cat.id}.html`),
    build({
      title: `${cat.label} commands — Insomniacs Bot`,
      description: `${cat.label}: ${names.join(', ')}. Syntax, examples and parameters for each command.`,
      url: `${SITE}/commands/${cat.id}`,
      initialCategory: cat.id,
    }),
  );
}

console.log(`Generated docs/commands/index.html and ${categories.length} category pages: ${categories.map((c) => c.id).join(', ')}`);
